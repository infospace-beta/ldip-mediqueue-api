CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_appointments_patient
        FOREIGN KEY (patient_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_doctor
        FOREIGN KEY (doctor_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_department
        FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointments_status
        CHECK (status IN ('BOOKED', 'CANCELLED', 'COMPLETED'))
);

CREATE UNIQUE INDEX uk_appointments_doctor_slot
    ON appointments (doctor_id, starts_at)
    WHERE status = 'BOOKED';

CREATE INDEX idx_appointments_patient_start
    ON appointments (patient_id, starts_at DESC);

CREATE TABLE clinical_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_ticket_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    authored_by_id BIGINT NOT NULL,
    diagnosis VARCHAR(2000) NOT NULL,
    treatment VARCHAR(4000) NOT NULL,
    prescription VARCHAR(2000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_clinical_records_queue_ticket UNIQUE (queue_ticket_id),
    CONSTRAINT fk_clinical_records_queue_ticket
        FOREIGN KEY (queue_ticket_id) REFERENCES queue_tickets(id) ON DELETE RESTRICT,
    CONSTRAINT fk_clinical_records_patient
        FOREIGN KEY (patient_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_clinical_records_author
        FOREIGN KEY (authored_by_id) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE INDEX idx_clinical_records_patient_created
    ON clinical_records (patient_id, created_at DESC);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    title VARCHAR(150) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_notifications_kind
        CHECK (kind IN ('QUEUE', 'APPOINTMENT', 'EMERGENCY', 'CLINICAL'))
);

CREATE INDEX idx_notifications_recipient_created
    ON notifications (recipient_id, created_at DESC);

CREATE INDEX idx_notifications_unread
    ON notifications (recipient_id, created_at DESC)
    WHERE read_at IS NULL;
