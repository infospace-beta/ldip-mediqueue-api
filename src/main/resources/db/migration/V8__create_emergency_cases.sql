CREATE TABLE emergency_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL,
    patient_id BIGINT,
    reported_by_id BIGINT NOT NULL,
    assigned_responder_id BIGINT,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'REPORTED',
    resolved_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_emergency_cases_hospital
        FOREIGN KEY (hospital_id) REFERENCES hospitals(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emergency_cases_patient
        FOREIGN KEY (patient_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emergency_cases_reporter
        FOREIGN KEY (reported_by_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emergency_cases_responder
        FOREIGN KEY (assigned_responder_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_emergency_cases_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_emergency_cases_status
        CHECK (status IN ('REPORTED', 'ASSIGNED', 'RESPONDING', 'RESOLVED'))
);

CREATE INDEX idx_emergency_cases_hospital_status_created
    ON emergency_cases (hospital_id, status, created_at DESC);
