CREATE TABLE queue_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    called_at TIMESTAMP WITHOUT TIME ZONE,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_queue_tickets_patient
        FOREIGN KEY (patient_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_queue_tickets_department
        FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
    CONSTRAINT chk_queue_tickets_status
        CHECK (status IN ('WAITING', 'CALLED', 'SKIPPED', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX idx_queue_tickets_department_status_created
    ON queue_tickets (department_id, status, created_at);

CREATE INDEX idx_queue_tickets_patient_created
    ON queue_tickets (patient_id, created_at DESC);

CREATE UNIQUE INDEX uk_queue_tickets_active_patient_department
    ON queue_tickets (patient_id, department_id)
    WHERE status IN ('WAITING', 'CALLED');
