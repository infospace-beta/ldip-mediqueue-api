-- 1. Extend hospitals table
ALTER TABLE hospitals
    ADD COLUMN registration_number VARCHAR(50),
    ADD COLUMN hospital_type VARCHAR(30) NOT NULL DEFAULT 'PUBLIC',
    ADD COLUMN county VARCHAR(100),
    ADD COLUMN town VARCHAR(100),
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';

-- 2. Add unique registration number constraint
CREATE UNIQUE INDEX uk_hospitals_registration_number
    ON hospitals (registration_number)
    WHERE registration_number IS NOT NULL;

-- 3. Validate hospital types
ALTER TABLE hospitals
    ADD CONSTRAINT chk_hospitals_type
    CHECK (hospital_type IN ('PUBLIC', 'PRIVATE', 'FAITH_BASED'));

-- 4. Validate hospital statuses
ALTER TABLE hospitals
    ADD CONSTRAINT chk_hospitals_status
    CHECK (status IN ('ACTIVE', 'INACTIVE'));

-- 5. Create departments table
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hospital_id BIGINT NOT NULL,

    name VARCHAR(150) NOT NULL,
    code VARCHAR(30) NOT NULL,
    description VARCHAR(500),

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_departments_hospital
        FOREIGN KEY (hospital_id)
        REFERENCES hospitals(id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_departments_hospital_name
        UNIQUE (hospital_id, name),

    CONSTRAINT uk_departments_hospital_code
        UNIQUE (hospital_id, code),

    CONSTRAINT chk_departments_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 6. Index for retrieving departments by hospital
CREATE INDEX idx_departments_hospital_id
    ON departments (hospital_id);
